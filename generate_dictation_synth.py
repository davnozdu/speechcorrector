def corrupt_endings(text: str, rng: random.Random, n_words: int = 2) -> str:
    words = text.split()
    candidates = []
    for idx, w in enumerate(words):
        clean_w = w.strip(".,?!:;—«»\"()").lower()
        if len(clean_w) >= 5 and re.fullmatch(r"[а-яё]+", clean_w):
            for suf, repls in ENDING_SWAPS:
                if clean_w.endswith(suf) and len(clean_w) - len(suf) >= 3:
                    candidates.append((idx, suf, repls))
                    break
    if not candidates:
        return text
    rng.shuffle(candidates)
    for idx, suf, repls in candidates[:n_words]:
        w = words[idx]
        low = w.lower()
        pos = low.rfind(suf)
        if pos != -1:
            new_suf = rng.choice(repls)
            words[idx] = w[:pos] + new_suf + w[pos + len(suf):]
    return " ".join(words)


