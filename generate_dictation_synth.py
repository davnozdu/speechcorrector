PUNCT_RE = re.compile(r"[.,?!:;…—«»\"()]+")
SPACE_RE = re.compile(r"\s+")


def corrupt_modern(target: str, rng: random.Random) -> Tuple[str, str]:
    r = rng.random()
    if r < 0.10:
        return target, "identity"

    s = target
    mode = "strip_all"
    if r < 0.50:
        # Полный сброс пунктуации и регистра
        s = PUNCT_RE.sub(" ", s)
        s = SPACE_RE.sub(" ", s).strip().lower()
        if rng.random() < 0.7:
            s = s.replace("ё", "е")
    elif r < 0.80:
        # Частичная кривая пунктуация GigaAM
        mode = "gigaam_partial"
        s = re.sub(r"[«»\"():;—]", " ", s)
        s = re.sub(r",", lambda m: "" if rng.random() < 0.75 else ("." if rng.random() < 0.3 else ","), s)
        s = re.sub(r"[.?!]", lambda m: "" if rng.random() < 0.5 else ".", s)
        s = SPACE_RE.sub(" ", s).strip()
        words = [w.lower() if rng.random() < 0.7 else w for w in s.split()]
        s = " ".join(words)
        if rng.random() < 0.7:
            s = s.replace("ё", "е")
    else:
        mode = "asr_errors"
        s = PUNCT_RE.sub(" ", s)
        s = SPACE_RE.sub(" ", s).strip().lower()
        s = s.replace("ё", "е")

    # В 45% случаев добавляем реалистичные речевые/ASR-ошибки
    if mode == "asr_errors" or rng.random() < 0.40:
        for good, bads in ASR_WORD_MAP.items():
            if good in s and rng.random() < 0.55:
                s = s.replace(good, rng.choice(bads), 1)
                mode = "asr_errors"
                break

    # Иногда добавляем повтор слова (заикание/пауза при диктовке)
    if rng.random() < 0.12:
        words = s.split()
        if len(words) >= 4:
            idx = rng.randint(0, len(words) - 2)
            words.insert(idx, words[idx])
            s = " ".join(words)
            mode = "asr_errors"

    return s, mode


def build_synth_dataset(out_path: Path, n_samples: int = 3000, seed: int = 123):
    rng = random.Random(seed)
    rows = []

    # 1. Добавляем все кураторские фразы (по 3 разных варианта искажения на каждую)
    for clean in CURATED_CLEAN:
        for _ in range(3):
            src, mode = corrupt_modern(clean, rng)
            rows.append({"source": src, "target": clean, "mode": mode, "book": "synth_curated"})

    # 2. Добавляем пары самоисправлений / оговорок (с повторением x4 для веса)
    for src, tgt in SELF_CORRECTION_PAIRS:
        for _ in range(4):
            rows.append({"source": src, "target": tgt, "mode": "self_correction", "book": "synth_self_corr"})

    # 2b. Генерируем ~2200 примеров транслитерации и выравнивания английских/AI терминов (DeepSeek, GitHub и др.)
    for _ in range(2200):
        # Повышенный вес для DeepSeek, DeepSeek 4.1 Flash, GitHub, Google Colab, Gemini, ONNX Runtime, PyTorch, macOS
        if rng.random() < 0.35:
            good, bads = rng.choice(TECH_BRAND_VARIANTS[:8])
        else:
            good, bads = rng.choice(TECH_BRAND_VARIANTS)
        good2, bads2 = rng.choice(TECH_BRAND_VARIANTS)
        while good2 == good:
            good2, bads2 = rng.choice(TECH_BRAND_VARIANTS)
        bad = rng.choice(bads)
        bad2 = rng.choice(bads2)

        src_tpl, tgt_tpl = rng.choice(BRAND_SENTENCE_TEMPLATES)
        src = src_tpl.format(bad=bad, bad2=bad2)
        tgt = tgt_tpl.format(good=good, good2=good2)

        if rng.random() < 0.25:
            src = src[0].upper() + src[1:] + "."
        if rng.random() < 0.30:
            for g_word, b_words in ASR_WORD_MAP.items():
                if g_word in src:
                    src = src.replace(g_word, rng.choice(b_words), 1)
                    break
        rows.append({"source": src, "target": tgt, "mode": "brand_translit", "book": "synth_brands"})

    # 2d. Генерируем 300 примеров списков/перечислений (чтобы модель не глотала слова)
    for _ in range(300):
        grp = list(rng.choice(LIST_GROUPS))
        rng.shuffle(grp)
        src_tpl, tgt_tpl = rng.choice(LIST_TEMPLATES)
        src = src_tpl.format(a=grp[0], b=grp[1], c=grp[2], d=grp[3])
        tgt = tgt_tpl.format(a=grp[0], b=grp[1], c=grp[2], d=grp[3])
        rows.append({"source": src, "target": tgt, "mode": "lists", "book": "synth_lists"})

    # 2e. Генерируем 1500 контрастных пар: 1100 косвенных вопросов/просьб (ТОЧКА) + 400 прямых вопросов (ВОПРОС)
    for _ in range(1100):
        lead = rng.choice(INDIRECT_DOT_LEADS)
        clause = rng.choice(INDIRECT_CLAUSES)
        tgt = f"{lead} {clause}."
        # Половина — полная очистка, половина — с ложным '?' на входе (чтобы модель училась убирать лишний '?')
        base = PUNCT_RE.sub(" ", tgt)
        base = SPACE_RE.sub(" ", base).strip().lower()
        if rng.random() < 0.35:
            base = base + "?"
        if rng.random() < 0.5:
            base = base.replace("ё", "е")
        rows.append({"source": base, "target": tgt, "mode": "indirect_dot", "book": "synth_qmark"})

    for _ in range(400):
        tgt = rng.choice(DIRECT_Q_PAIRS)
        base = PUNCT_RE.sub(" ", tgt)
        base = SPACE_RE.sub(" ", base).strip().lower()
        if rng.random() < 0.35:
            base = base + "."
        if rng.random() < 0.5:
            base = base.replace("ё", "е")
        rows.append({"source": base, "target": tgt, "mode": "direct_qmark", "book": "synth_qmark"})

    # 2c. Генерируем ~1500 примеров с испорченными окончаниями / согласованием
    for src, tgt in ENDING_PAIR_CURATED:
        for _ in range(10):
            rows.append({"source": src, "target": tgt, "mode": "ending_errors", "book": "synth_endings"})

    # Берём реальные фразы из книг (train.jsonl) + CURATED_CLEAN и портим в них 1-2 окончания + пунктуацию
    book_targets = list(CURATED_CLEAN)
    book_train = Path("/Users/davnozdu/Downloads/speechcorrector/data/train.jsonl")
    if book_train.exists():
        with book_train.open("r", encoding="utf-8") as bf:
            for i, line in enumerate(bf):
                if i >= 6000:
                    break
                book_targets.append(json.loads(line)["target"])
    rng.shuffle(book_targets)
    added_end = 0
    for tgt in book_targets:
        if added_end >= 1350:
            break
        base = PUNCT_RE.sub(" ", tgt)
        base = SPACE_RE.sub(" ", base).strip().lower()
        corrupted = corrupt_endings(base, rng, n_words=rng.choice([1, 2]))
        if corrupted != base:
            rows.append({"source": corrupted, "target": tgt, "mode": "ending_errors", "book": "synth_endings"})
            added_end += 1

    # 3. Генерируем разнообразные современные фразы диктовки
    seen_targets = set(CURATED_CLEAN)
    while len(rows) < n_samples:
        kind = rng.random()
        if kind < 0.45:
            intro = rng.choice(INTROS)
            act1, act2 = rng.choice(SUBJECTS_ACTIONS)
            obj = rng.choice(OBJECTS)
            if intro and not intro.endswith(("! ", "? ")):
                sent = f"{intro}{act1} {obj}, {act2}."
            else:
                sent = f"{intro}{act1[0].upper()}{act1[1:]} {obj}, {act2}."
        elif kind < 0.72:
            q1, q2 = rng.choice(QUESTIONS)
            sent = f"{q1} {q2}?"
        else:
            tpl = rng.choice(MEETING_TEMPLATES)
            sent = tpl.format(
                person_dat=rng.choice(PEOPLE_DAT),
                person_ins=rng.choice(PEOPLE_INS),
                time=rng.choice(TIMES),
                shift_time=rng.choice(SHIFT_TIMES),
                place=rng.choice(PLACES),
                obj=rng.choice(OBJECTS),
            )

        # Иногда склеиваем 2 коротких предложения
        if rng.random() < 0.25:
            second = rng.choice(CURATED_CLEAN)
            sent = f"{sent} {second}"

        src, mode = corrupt_modern(sent, rng)
        rows.append({"source": src, "target": sent, "mode": mode, "book": "synth_generated"})
        seen_targets.add(sent)

    rng.shuffle(rows)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    modes = {}
    for r in rows:
        modes[r["mode"]] = modes.get(r["mode"], 0) + 1
    print(f"Wrote {len(rows)} modern dictation pairs to {out_path} | modes: {modes}")
    for r in rows[:6]:
        print(f"  [{r['mode']}]")
        print(f"    IN : {r['source']}")
        print(f"    OUT: {r['target']}")


